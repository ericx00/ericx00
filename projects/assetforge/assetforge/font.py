GW, GH, ADVANCE, LINE = 5, 7, 6, 9
ORDER = sorted(G, key=lambda ch: (not ch.isalpha(), not ch.isdigit(), ch))


def glyph(ch: str) -> list[str]:
    return G.get(ch.upper(), G["?"])


def text_width(text: str, scale: int = 1) -> int:
    return max(0, len(text) * ADVANCE - 1) * scale


def draw_text(c: Canvas, x: int, y: int, text: str, col: RGBA, scale: int = 1, shadow: RGBA | None = None) -> None:
    for i, ch in enumerate(text):
        rows = glyph(ch)
        for gy, row in enumerate(rows):
            for gx, v in enumerate(row):
                if v == "#":
                    px, py = x + (i * ADVANCE + gx) * scale, y + gy * scale
                    if shadow:
                        c.fill_rect(px + scale, py + scale, scale, scale, shadow)
                    c.fill_rect(px, py, scale, scale, col)
    if shadow:  # redraw glyphs over shadows of neighbours
        for i, ch in enumerate(text):
            for gy, row in enumerate(glyph(ch)):
                for gx, v in enumerate(row):
                    if v == "#":
                        c.fill_rect(x + (i * ADVANCE + gx) * scale, y + gy * scale, scale, scale, col)


def atlas(cols: int = 16) -> tuple[Canvas, dict[str, tuple[int, int]]]:
    """White glyphs on transparent, 6x8 cells. Returns the canvas and char -> (x, y)."""
    rows = (len(ORDER) + cols - 1) // cols
    c = Canvas(cols * ADVANCE, rows * (GH + 1))
    pos = {}
    for i, ch in enumerate(ORDER):
        x, y = (i % cols) * ADVANCE, (i // cols) * (GH + 1)
        pos[ch] = (x, y)
        draw_text(c, x, y, ch, (255, 255, 255, 255))
    return c, pos


def bmfont(png_name: str, size: tuple[int, int], pos: dict[str, tuple[int, int]], face: str = "Forge 5x7") -> str:
    """AngelCode BMFont text format. Lowercase letters point at the uppercase glyphs."""
    lines = [
        f'info face="{face}" size={GH} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={LINE} base={GH} scaleW={size[0]} scaleH={size[1]} pages=1 packed=0",
        f'page id=0 file="{png_name}"',
    ]
    chars = []
    for ch, (x, y) in pos.items():
        chars.append((ord(ch), x, y))
        if ch.isalpha():
            chars.append((ord(ch.lower()), x, y))
    chars.sort()
    lines.append(f"chars count={len(chars)}")
    for cid, x, y in chars:
        lines.append(f"char id={cid} x={x} y={y} width={GW} height={GH} xoffset=0 yoffset=0 xadvance={ADVANCE} page=0 chnl=15")
    return "\n".join(lines) + "\n"
