def build_fonts_free(out: Path) -> Path:
    root = out / "forge-pixel-fonts-free"
    keys = list(pixfonts.fonts())
    names, ttf = _fonts(root, keys)
    fs = pixfonts.fonts()
    font_sheet(keys).scaled(3).save(root / "previews" / "fonts.png")
    sizes = {"sans": 16, "bold": 16, "display": 32, "tiny": 12}
    faces = "".join(f"@font-face{{font-family:'{fs[k].name}';src:url('fonts/ttf/{fs[k].file}.ttf')}}" for k in keys)
    rows = "".join(f"<small>{fs[k].name}, {sizes[k]} px</small><p style=\"font:{sizes[k]}px '{fs[k].name}'\">The quick brown fox jumps over the lazy dog 0123456789</p>" for k in keys)
    (root / "demo.html").write_text(FONT_DEMO.format(faces=faces, rows=rows))
    contents = [f"{len(names)} pixel fonts: {', '.join(names)}", ("TTF (works in any engine, editor or website) and " if ttf else "") + "BMFont (.fnt + PNG at 1x and 2x)",
                "Printable ASCII: letters, digits and punctuation (" + str(len(fs["sans"].glyphs)) + " glyphs in Forge Sans)", "`demo.html`: type your own text and see all four fonts"]
    (root / "README.md").write_text(
        "# Forge Pixel Fonts (free)\n\nFour pixel fonts for games, free for commercial use.\n\n## What is inside (counted by the build)\n\n" + "\n".join(f"- {c}" for c in contents) +
        "\n\n## The fonts\n\n" + "\n".join(f"- **{fs[k].name}** (`{fs[k].file}`): {fs[k].note}" for k in keys) +
        "\n\n## Tips\n\n- Use the listed pixel sizes (or whole multiples) and turn antialiasing off, or the letters blur.\n"
        "- Godot: import the .ttf, set Antialiasing to None, or import the .fnt as a FontFile.\n- Unity: import the .ttf, Rendering Mode = Hinted Raster, Character = ASCII default set; or use the BMFont files with a bitmap-font importer.\n"
        "- Web: `@font-face` with the .ttf and `font-smooth: never; -webkit-font-smoothing: none`.\n\n"
        "## Honest notes\n\n- English letters only: no accents, Cyrillic or CJK yet.\n- Forge Sans Bold and Forge Display are made from Forge Sans by code (thickened / doubled with smoothed corners).\n"
        "- Ember Tiny has capitals, digits and punctuation; lowercase letters show as capitals.\n\n"
        f"More from Forge (card frames, icons, UI, sounds, effects): itch.io or {STORE}\n")
    lic = root / "LICENSE.txt"
    lic.write_text(LICENSE.format(title="Forge Pixel Fonts (free)", version=__version__).replace("You may NOT resell", "These fonts are free. You may embed them in games and apps. You may NOT resell"))
    (root / "metadata.json").write_text(json.dumps({"version": __version__, "fonts": names, "ttf": ttf, "contents": contents}, indent=1))
    return root


def build(out: Path, zip_packs: bool = True) -> list[Path]:
    packs = [build_vfx(out), build_vfx_free(out), build_card_sfx(out), build_fonts_free(out)]
    if zip_packs:
        for p in packs:
            _zip(p)
    return packs
